// Bundles the notification email templates (emails/notifications.ts and the
// .tsx files it re-exports) into one plain-JS module for the API functions.
// Vercel's Node functions can compile .ts imports but not .tsx ones, so the
// templates have to arrive as JS. Runs as part of `npm run build`.
import { build } from 'esbuild';

await build({
  entryPoints: ['emails/notifications.ts'],
  outfile: 'api/_lib/email-templates.generated.js',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  jsx: 'automatic',
  // React and React Email are installed at the root and traced into each
  // function from node_modules.
  packages: 'external',
  banner: { js: '// Generated by scripts/build-email-templates.mjs from emails/. Do not edit.' },
  logLevel: 'warning',
});

// ── Email-client check ───────────────────────────────────────────────────────
// Browsers (and the React Email preview) handle CSS that Gmail doesn't. Gmail
// throws away an element's entire style attribute if any part of it is
// unsupported, so one stray utility can strip a card's background, width and
// border. Render every template with its PreviewProps and fail the build if
// an inline style uses something we know gets dropped.
const UNSUPPORTED = [
  { pattern: /var\(/, why: 'CSS variable (e.g. shadow-*, ring-*)' },
  { pattern: /oklch\(/, why: 'oklch() color' },
  { pattern: /display:\s*(inline-)?flex|display:\s*grid/, why: 'flexbox/grid layout' },
  { pattern: /calc\(/, why: 'calc()' },
];

const { createElement } = await import('react');
const { render } = await import('react-email');
const templates = await import(new URL('../api/_lib/email-templates.generated.js', import.meta.url).href);

const problems = [];
for (const [name, Template] of Object.entries(templates)) {
  if (typeof Template !== 'function' || !Template.PreviewProps) continue;
  const html = await render(createElement(Template, Template.PreviewProps));
  for (const [, tag, style] of html.matchAll(/<(\w+)[^>]*?\sstyle="([^"]*)"/g)) {
    for (const { pattern, why } of UNSUPPORTED) {
      if (pattern.test(style)) problems.push(`${name} <${tag}>: ${why}\n    style="${style.slice(0, 160)}…"`);
    }
  }
}

if (problems.length > 0) {
  console.error(`Email templates use CSS that Gmail strips:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
