// Bundles the notification email templates (emails/notifications.ts and the
// .tsx files it re-exports) into one plain-JS module for the API functions.
// Vercel's Node functions can compile .ts imports but not .tsx ones, so the
// templates have to arrive as JS. Runs as part of `npm run build`.
import { build } from 'esbuild';

await build({
  entryPoints: ['emails/notifications.ts'],
  outfile: 'api/_lib/email-templates.generated.js',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  jsx: 'automatic',
  // React and React Email are installed at the root and traced into each
  // function from node_modules.
  packages: 'external',
  banner: { js: '// Generated by scripts/build-email-templates.mjs from emails/. Do not edit.' },
  logLevel: 'warning',
});
